"""Bind the finite-cutoff calculation to its exact report and paper constants."""

import hashlib
import json
from fractions import Fraction as F
from pathlib import Path

from koikoi.train import provenance


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def export():
    report_path = Path("runs/observer_trace_identity_cpu.json")
    assert (
        sha(report_path)
        == "830420c471986c33b84bfd3a9a8d2b86f7aaef5bd343637856d4e682b4006d60"
    )
    report = json.loads(report_path.read_text(encoding="utf-8"))
    assert report["status"] == "passed" and report["pathwise_exact_cases"] == 6048
    assert report["production_source_sha256"] == provenance()["source_sha256"]
    inputs = report["inputs"] | {
        str(report_path): sha(report_path),
        str(Path(__file__)): sha(__file__),
    }
    assert all(sha(p) == h for p, h in inputs.items())
    means = ((F(1, 5), F(21, 100)), (F(1), F(-1)))
    marginal = [sum(row[a] for row in means) / 2 for a in (0, 1)]
    coefficients = (F(1), F(-1, 100))
    truth = sum(coefficients[x] * (means[x][1] - means[x][0]) / 8 for x in (0, 1))
    covariance = sum(
        coefficients[x] * (a - F(1, 2)) * (marginal[a] - means[x][a]) / 4
        for x in (0, 1)
        for a in (0, 1)
    )
    assert truth == F(3, 800) and covariance == F(-20301, 160000)
    cases = report["toy"]["cases"]
    assert len(cases) == 16
    for boundary in ("terminal", "cutoff"):
        for mode in ("observer", "signed"):
            for lam in (F(0), F(37, 100), F(19, 20), F(1)):
                key = f"{boundary}_{mode}_lambda{lam}"
                bias = (
                    F(0)
                    if mode == "observer"
                    else covariance * (1 - lam if boundary == "terminal" else 1)
                )
                row = cases[key]
                assert F(row["exact_gradient"]) == truth + bias
                assert F(row["exact_bias"]) == bias
                assert abs(row["cpu_gradient"] - float(truth + bias)) < 3e-8
    cutoff = truth + covariance
    folder = Path("docs/paper/generated")
    constants = folder / "observer_trace_constants.tex"
    content = (
        "% Generated by scripts.export_observer_trace_evidence; exact fractions.\n"
        rf"\newcommand{{\TraceSignedCutoff}}{{-\frac{{{-cutoff.numerator}}}{{{cutoff.denominator}}}}}"
        + "\n"
        rf"\newcommand{{\TraceScoreCovariance}}{{-\frac{{{-covariance.numerator}}}{{{covariance.denominator}}}}}"
        + "\n"
        r"\newcommand{\TraceExactCases}{6,048}" + "\n"
    ).encode("utf-8")
    ledger = folder / "observer_trace_evidence.json"
    result = {
        "status": "passed",
        "inputs": inputs,
        "outputs": {str(constants): hashlib.sha256(content).hexdigest()},
        "pathwise_exact_cases": 6048,
        "true_gradient": str(truth),
        "cross_observer_score_covariance": str(covariance),
        "cutoff_signed_gradient": str(cutoff),
        "verified_cases": cases,
        "scope": report["scope"],
    }
    payload = (json.dumps(result, indent=2) + "\n").encode("utf-8")
    for path, data in ((constants, content), (ledger, payload)):
        if path.exists() and path.read_bytes() != data:
            raise ValueError(f"Refusing to overwrite different evidence: {path}")
    folder.mkdir(parents=True, exist_ok=True)
    constants.write_bytes(content)
    ledger.write_bytes(payload)
    print(json.dumps({"ledger_sha256": sha(ledger), "verified_cases": len(cases)}))


if __name__ == "__main__":
    export()
